type AnswerSet = (chat: boolean, prices?: PackagePrices | null) => Record<number, string>;

/** Each country's questions and its new-cycle / credit-on-interest answers */
/** The credit line each set's answers use, and what it becomes with the free «مهتم» reply */
interface CreditLines {
  plain: string;
  withFreeReply: string;
}
const MSA_CREDIT: CreditLines = { plain: CREDIT_ON_INTEREST_LINE, withFreeReply: creditLine(true) };

const FAQ_SETS: Record<CountryCode, { base: typeof baseFaqs; newCycle: AnswerSet; creditOnInterest: AnswerSet; credit: CreditLines }> = {
  JO: { base: baseFaqs, newCycle: newCycleAnswers, creditOnInterest: creditOnInterestAnswers, credit: MSA_CREDIT },
  SA: { base: saBaseFaqs, newCycle: saNewCycleAnswers, creditOnInterest: saCreditOnInterestAnswers, credit: MSA_CREDIT },
  LB: {
    base: lbBaseFaqs,
    newCycle: lbNewCycleAnswers,
    creditOnInterest: lbCreditOnInterestAnswers,
    credit: { plain: LB_CREDIT_ON_INTEREST_LINE, withFreeReply: lbCreditLine(true) },
  },
};

/** FAQ for the visitor's country (Jordan = the original answers) */
/** `freeReply`: switch `free_interest_reply` (only with credit on interest) adds the free-reply line */
export function faqsFor(newCycle: boolean, chat: boolean, creditOnInterest = false, country: CountryCode = "JO", prices?: PackagePrices | null, freeReply = false) {
  const set = FAQ_SETS[country];
  const overrides: Record<number, string> = newCycle
    ? { ...set.newCycle(chat, prices), ...(creditOnInterest ? set.creditOnInterest(chat, prices) : {}) }
    : {};
  const withFree = (a: string) =>
    creditOnInterest && freeReply ? a.replace(set.credit.plain, set.credit.withFreeReply) : a;
  return set.base.map((f) => (overrides[f.id] ? { ...f, a: withFree(overrides[f.id]) } : f));
}

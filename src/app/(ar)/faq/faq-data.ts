type AnswerSet = (chat: boolean, prices?: PackagePrices | null) => Record<number, string>;

/** Each country's questions and its new-cycle / credit-on-interest answers */
const FAQ_SETS: Record<CountryCode, { base: typeof baseFaqs; newCycle: AnswerSet; creditOnInterest: AnswerSet }> = {
  JO: { base: baseFaqs, newCycle: newCycleAnswers, creditOnInterest: creditOnInterestAnswers },
  SA: { base: saBaseFaqs, newCycle: saNewCycleAnswers, creditOnInterest: saCreditOnInterestAnswers },
  LB: { base: lbBaseFaqs, newCycle: lbNewCycleAnswers, creditOnInterest: lbCreditOnInterestAnswers },
};

/** FAQ for the visitor's country (Jordan = the original answers) */
/** `freeReply`: switch `free_interest_reply` (only with credit on interest) adds the free-reply line */
export function faqsFor(newCycle: boolean, chat: boolean, creditOnInterest = false, country: CountryCode = "JO", prices?: PackagePrices | null, freeReply = false) {
  const set = FAQ_SETS[country];
  const overrides: Record<number, string> = newCycle
    ? { ...set.newCycle(chat, prices), ...(creditOnInterest ? set.creditOnInterest(chat, prices) : {}) }
    : {};
  const withFree = (a: string) =>
    creditOnInterest && freeReply ? a.replace(CREDIT_ON_INTEREST_LINE, creditLine(true)) : a;
  return set.base.map((f) => (overrides[f.id] ? { ...f, a: withFree(overrides[f.id]) } : f));
}

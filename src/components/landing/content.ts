/**
 * Landing page copy, chosen by the new-cycle switches so the page never describes
 * a feature that is switched off.
 */
import { CREDIT_ON_INTEREST_LINE } from "@/lib/suggestions/copy";

export interface LandingMode {
  /** Family / chat requests and per-request credits */
  introRequests: boolean;
  /** In-app chat before the family visit */
  chat: boolean;
  /** "مهتم" costs 1 credit and picks the introduction; match, requests and chat are free */
  creditOnInterest?: boolean;
}

export interface JourneyStep {
  title: string;
  text: string;
}

export interface FaqItem {
  q: string;
  a: string;
}

export function landingContent(mode: LandingMode) {
  const newCycle = mode.introRequests;
  const coi = newCycle && !!mode.creditOnInterest;

  const hero = {
    lead: coi
      ? "اقتراحات مدروسة باستمرار، وقرار مشترك بين الطرفين، ثم تعارف يرضي العائلتين."
      : newCycle
      ? "اقتراحات مدروسة كل أسبوع، وقرار مشترك بين الطرفين، ثم تعارف يرضي العائلتين."
      : "اقتراحات مدروسة، وقرار بستر واحترام، ثم زيارة عائلية على أصولها.",
    note: newCycle ? "التسجيل مجاني ومعه 3 أرصدة للتعارف" : "التسجيل مجاني ومعه اقتراحان",
    /** Three short reasons to start now, under the lead */
    points: newCycle
      ? ["3 أرصدة مجانية عند التسجيل", "الصور مخفية حتى التوافق", "لا يعرف أحد بقرار «لا»"]
      : ["اقتراحان مجاناً عند التسجيل", "الصور مخفية حتى التوافق", "لا يعرف أحد بقرارك"],
  };

  const steps: JourneyStep[] = newCycle
    ? [
        { title: "سجّل برقم هاتفك", text: "رمز تحقق يصلك على هاتفك الأردني وتبدأ مباشرة." },
        { title: "أكمل ملفك وتطلعاتك", text: "عرّف بنفسك وحدّد ما تبحث عنه في شريك الحياة. اختبار الشخصية يجعل الاقتراحات أدق." },
        coi
          ? { title: "اقتراحات مجانية باستمرار", text: "تصلك اقتراحات تناسب معاييرك مع نسبة التوافق، بدون صور. نُعلمك عندما يبدي أحدهم اهتمامه بك، أما قرار «لا» فلا يعرفه إلا من أبدى اهتمامه." }
          : { title: "اقتراحات أسبوعية مجانية", text: "تصلك اقتراحات تناسب معاييرك مع نسبة التوافق، بدون صور. نُعلمك عندما يبدي أحدهم اهتمامه بك، أما قرار «لا» فلا يعرفه إلا من أبدى اهتمامه." },
        coi
          ? { title: "توافق متبادل", text: "عندما يبدي الطرفان اهتمامهما تظهر الصور والتفاصيل الكاملة، ويبدأ التعارف الذي اخترتماه مباشرة." }
          : { title: "توافق متبادل", text: "عندما يبدي الطرفان اهتمامهما تظهر الصور والتفاصيل الكاملة للطرفين." },
      ]
    : [
        { title: "سجّل برقم هاتفك", text: "رمز تحقق يصلك على هاتفك الأردني وتبدأ مباشرة." },
        { title: "أكمل ملفك وتطلعاتك", text: "عرّف بنفسك وحدّد ما تبحث عنه في شريك الحياة. اختبار الشخصية يجعل الاقتراحات أدق." },
        { title: "استلم اقتراحات مدروسة", text: "اقتراحات مع تفاصيل كاملة ونسبة التوافق. تقبل أو تعتذر، بدون أن يعرف الطرف الآخر." },
        { title: "توافق متبادل", text: "عندما يقبل الطرفان تظهر الصور، ويتواصل فريق نصيبك مع أولياء الأمور لتنسيق الزيارة." },
      ];

  const paths = newCycle
    ? {
        title: coi ? "وتختاران طريقة التعارف مع «مهتم»" : "ثم تختاران طريقة التعارف",
        family: {
          title: "تعارف عائلي",
          text: coi
            ? "عند التوافق المتبادل يرى كل طرف اسم وليّ أمر الطرف الآخر ورقمه بموافقته، فتتواصل العائلتان مباشرة لترتيب الزيارة."
            : "بعد قبول الطلب يرى كل طرف اسم وليّ أمر الطرف الآخر ورقمه، فتتواصل العائلتان مباشرة لترتيب الزيارة.",
        },
        chat: mode.chat
          ? {
              title: "محادثة قبل الزيارة",
              text: "محادثة نصية خاصة داخل نصيبك لمدة 14 يوماً، تُمنع فيها مشاركة الأرقام والحسابات. وتنتقلان للتعارف العائلي متى شئتما.",
            }
          : null,
        cost: coi ? CREDIT_ON_INTEREST_LINE : "كل طلب تعارف يستخدم رصيداً واحداً من المُرسِل، والقبول مجاني.",
      }
    : null;

  const finish = newCycle
    ? { title: "زيارة العائلة", text: "العائلتان ترتّبان الزيارة بنفسيهما، ونسأل الله أن يكتب لكما الخير." }
    : { title: "زيارة العائلة", text: "زيارة عائلية تقليدية بإشراف الأهل، على عاداتنا الأردنية." };

  /** «نصيبك ليس تطبيق تعارف»: what usually happens elsewhere vs here, row by row */
  const compare: { topic: string; elsewhere: string; here: string }[] = [
    { topic: "الصور", elsewhere: "ظاهرة لكل من يتصفح", here: "مخفية حتى يقول الطرفان «مهتم»" },
    {
      topic: "التواصل",
      elsewhere: "رسائل من أي شخص في أي وقت",
      here: mode.chat
        ? "لا تواصل قبل التوافق المتبادل، ثم محادثة محدودة تحجب الأرقام والروابط"
        : newCycle
        ? "لا تواصل بين المستخدمين، بل تعارف بين العائلتين بعد التوافق"
        : "لا رسائل بين المستخدمين، وزيارة عائلية بعد التوافق",
    },
    {
      topic: "العائلة",
      elsewhere: "خارج الصورة",
      here: newCycle ? "جزء من الطريق: بيانات وليّ الأمر تُشارك بموافقتك عند التعارف العائلي" : "زيارة عائلية ينسّقها فريق نصيبك",
    },
    { topic: "الرفض", elsewhere: "قد يُكشف أو يُفهم", here: "قرار «لا» لا يعرف به أحد" },
    { topic: "الحسابات", elsewhere: "بريد إلكتروني أو حساب مجهول", here: "كل حساب مربوط برقم أردني مؤكَّد" },
    { topic: "الهدف", elsewhere: "تعارف عابر", here: "الزواج بالحلال" },
  ];

  const faqs: FaqItem[] = newCycle
    ? [
        {
          q: "هل نصيبك تطبيق تعارف؟",
          a: mode.chat
            ? "لا. نصيبك منصة للزواج بالحلال. لا يمكن التواصل قبل التوافق المتبادل، والمحادثة اختيارية ومحدودة بـ 14 يوماً وهدفها الوصول للتعارف العائلي."
            : "لا. نصيبك منصة للزواج بالحلال. لا تواصل بين المستخدمين، والخطوة بعد التوافق تعارف بين العائلتين.",
        },
        {
          q: "هل المنصة مجانية؟",
          a: coi
            ? `التسجيل والاقتراحات مجانية، وتحصل على 3 أرصدة عند التسجيل. ${CREDIT_ON_INTEREST_LINE} ويمكنك شحن رصيدك من لوحة التحكم.`
            : "التسجيل والاقتراحات مجانية، وتحصل على 3 أرصدة عند التسجيل. كل طلب تعارف عائلي أو محادثة يستخدم رصيداً واحداً من المُرسِل، ويمكنك شحن رصيدك من لوحة التحكم.",
        },
        {
          q: "متى تظهر بيانات وليّ أمري للطرف الآخر؟",
          a: coi
            ? "فقط عند التعارف العائلي في توافق متبادل، وبشرط موافقتك على المشاركة في هذا التوافق. قبل ذلك لا يراها أحد."
            : "فقط بعد قبول طلب التعارف العائلي من الطرفين، وبشرط موافقتك على المشاركة. قبل ذلك لا يراها أحد.",
        },
        ...(mode.chat
          ? [
              {
                q: "كيف تعمل المحادثة قبل الزيارة؟",
                a: coi
                  ? "إذا اختار الطرفان «محادثة هنا أولاً» مع «مهتم» تُفتح محادثة نصية فور التوافق، ويمكن طلبها مجاناً بعد التوافق أيضاً. تستمر 14 يوماً قابلة للتمديد مرة واحدة، وتُحجب الأرقام والروابط وحسابات التواصل تلقائياً."
                  : "بعد التوافق يمكن لأحد الطرفين إرسال طلب محادثة. عند القبول تُفتح محادثة نصية لمدة 14 يوماً قابلة للتمديد مرة واحدة. تُحجب الأرقام والروابط وحسابات التواصل تلقائياً.",
              },
            ]
          : []),
        {
          q: "هل الحسابات حقيقية؟",
          a: "كل حساب مربوط برقم هاتف أردني مؤكَّد برمز تحقق، ويمكن الإبلاغ عن أي حساب مشبوه في أي وقت.",
        },
      ]
    : [
        {
          q: "كيف تختلف نصيبك عن تطبيقات التعارف؟",
          a: "لا رسائل أو محادثات بين المستخدمين. اقتراحات مدروسة، وخصوصية تامة، وزيارات عائلية منظمة بإشراف الأهل.",
        },
        {
          q: "هل المنصة مجانية؟",
          a: "التسجيل مجاني ومعه اقتراحان مجاناً. كل اقتراح يستخدم رصيداً واحداً، ويمكنك شحن رصيدك من لوحة التحكم.",
        },
        {
          q: "كيف تتم الزيارة العائلية؟",
          a: "بعد التوافق المتبادل يتواصل فريق نصيبك مع وليّ أمر كل طرف لتنسيق زيارة عائلية تقليدية محترمة.",
        },
        {
          q: "هل الحسابات حقيقية؟",
          a: "كل حساب مربوط برقم هاتف أردني مؤكَّد برمز تحقق، ويمكن الإبلاغ عن أي حساب مشبوه في أي وقت.",
        },
      ];

  const cta = {
    title: "ابدأ خطوتك الأولى نحو نصف دينك",
    text: coi
      ? "سجّل مجاناً، واحصل على 3 أرصدة للتعارف واقتراحات مجانية باستمرار."
      : newCycle
      ? "سجّل مجاناً، واحصل على 3 أرصدة للتعارف واقتراحات أسبوعية مجانية."
      : "سجّل مجاناً، وأول اقتراحين علينا.",
  };

  return { hero, steps, paths, finish, compare, faqs, cta };
}

export type LandingContent = ReturnType<typeof landingContent>;

import { z } from "zod/v4";

export const profileSchema = z.object({
  dateOfBirth: z.string().min(1, "تاريخ الميلاد مطلوب"),
  city: z.string().min(1, "المدينة مطلوبة"),
  nationality: z.string().min(1, "الجنسية مطلوبة"),
  education: z.string().min(1, "المستوى التعليمي مطلوب"),
  fieldOfStudy: z.string().min(1, "التخصص مطلوب"),
  job: z.string().min(1, "الوظيفة مطلوبة"),
  incomeRange: z.string().min(1, "مستوى الدخل مطلوب"),
  height: z.number().min(100).max(250),
  weight: z.number().min(30).max(300),
  skinColor: z.string().min(1, "لون البشرة مطلوب"),
  childrenCount: z.number().min(0).max(20),
  willingToRelocate: z.string().min(1, "الاستعداد للانتقال مطلوب"),
  maritalStatus: z.string().min(1, "الحالة الاجتماعية مطلوبة"),
  religiosity: z.string().min(1, "مستوى التدين مطلوب"),
  familyValues: z.string().min(1, "القيم العائلية مطلوبة").max(500, "الحد الأقصى 500 حرف"),
  partnerExpectations: z.string().min(1, "مواصفات الشريك مطلوبة").max(500, "الحد الأقصى 500 حرف"),
  hobbies: z.string().min(1, "الهوايات مطلوبة"),
  interests: z.string().min(1, "الاهتمامات مطلوبة"),
  lifestyle: z.string().min(1, "نمط الحياة مطلوب"),
  hijab: z.boolean().optional(),
  smokingStatus: z.string().min(1, "حالة التدخين مطلوبة"),
  aboutMe: z.string().min(1, "نبذة عنك مطلوبة").max(500, "الحد الأقصى 500 حرف"),
  area: z.string().min(1, "المنطقة مطلوبة"),
  latitude: z.number().optional(),
  longitude: z.number().optional(),
  tribe: z.string().min(1, "العشيرة مطلوبة"),
  familyOriginArea: z.string().min(1, "منطقة أصل العائلة مطلوبة"),
  numberOfSiblings: z.number().min(0).max(20),
  housingType: z.string().min(1, "نوع السكن مطلوب"),
  beard: z.boolean().optional(),
  cookingAbility: z.string().min(1, "مهارة الطبخ مطلوبة"),
  drivingLicense: z.boolean(),
  healthConditions: z.string().min(1, "الحالات الصحية مطلوبة").max(500, "الحد الأقصى 500 حرف"),
  monthlyExpenses: z.string().min(1, "المصاريف الشهرية مطلوبة"),
  wantsPhoto: z.boolean().optional(),
  prefAgeMin: z.number().min(18).max(70),
  prefAgeMax: z.number().min(18).max(70),
  prefCity: z.array(z.string()).min(1, "المدينة المفضلة مطلوبة"),
  prefEducation: z.array(z.string()).min(1, "المستوى التعليمي المفضل مطلوب"),
  prefMaritalStatus: z.array(z.string()).min(1, "الحالة الاجتماعية المفضلة مطلوبة"),
});

export const parentInfoSchema = z.object({
  parentName: z.string().min(2, "اسم ولي الأمر مطلوب"),
  parentPhone: z.string().min(10, "رقم الهاتف غير صالح"),
  relationship: z.enum(["father", "mother", "brother", "guardian"]),
  address: z.string().min(5, "العنوان مطلوب"),
  notes: z.string().optional(),
});

export type ProfileInput = z.infer<typeof profileSchema>;
export type ParentInfoInput = z.infer<typeof parentInfoSchema>;
